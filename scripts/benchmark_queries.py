"""Benchmark naive vs optimised queries with PROFILE and write docs/benchmarks.md.

For each pair we report database hits (work done by the engine), server time,
and the main plan operators, so the effect of an index or a rewrite is visible.
"""

from __future__ import annotations

import logging
import statistics
from pathlib import Path

from app.config import get_settings
from app.database import Neo4jClient
from app.queries import cypher

logger = logging.getLogger("benchmark")
RUNS = 5
OUTPUT = Path(__file__).resolve().parent.parent / "docs" / "benchmarks.md"

CASES = [
    {
        "name": "Airport lookup: no label vs unique-constraint index",
        "why": "Without a label the planner must scan every node; with :Airport {iata} it seeks the constraint index.",
        "naive": "MATCH (a) WHERE a.iata = $iata RETURN a.name AS name",
        "optimised": "MATCH (a:Airport {iata: $iata}) RETURN a.name AS name",
        "params": {"iata": "CDG"},
    },
    {
        "name": "Search: toLower(name) CONTAINS vs TEXT index on search_text",
        "why": "A function on the property defeats every index; a pre-lowercased property with a TEXT index is used.",
        "naive": "MATCH (a:Airport) WHERE toLower(a.name) CONTAINS $q RETURN a.iata AS iata LIMIT 20",
        "optimised": "MATCH (a:Airport) WHERE a.search_text CONTAINS $q RETURN a.iata AS iata LIMIT 20",
        "params": {"q": "paris"},
    },
    {
        "name": "Airline hubs: scan ROUTE.airlines lists vs SERVES relationships",
        "why": "Modeling choice: SERVES turns a scan of all 37k routes into an index seek + expansion.",
        "naive": cypher.AIRLINE_HUBS_NAIVE,
        "optimised": cypher.AIRLINE_HUBS,
        "params": {"code": "AF", "limit": 10},
    },
    {
        "name": "Reachability within 3 hops: variable-length path vs ANY SHORTEST",
        "why": ("Hypothesis disproved. With count(DISTINCT dst) the planner already uses a pruning "
                "breadth-first VarLengthExpand, so the 'naive' query is the fast one. ANY SHORTEST "
                "computes one shortest path per destination: slower, but it returns the hop level, "
                "which the endpoint needs."),
        "naive": cypher.REACHABLE_NAIVE_3,
        "optimised": cypher.REACHABLE_BY_HOPS[3],
        "params": {"iata": "LYS", "sample": 5},
    },
    {
        "name": "Geo search: computed distance on all airports vs POINT index",
        "why": ("point.distance on raw lat/lon must be computed for every airport; "
                "on `location` the POINT index prunes."),
        "naive": (
            "MATCH (a:Airport) WHERE point.distance(point({latitude: a.latitude, longitude: a.longitude}), "
            "point({latitude: $lat, longitude: $lon})) < $radius_m RETURN a.iata AS iata"
        ),
        "optimised": (
            "MATCH (a:Airport) WHERE point.distance(a.location, point({latitude: $lat, longitude: $lon})) < $radius_m "
            "RETURN a.iata AS iata"
        ),
        "params": {"lat": 48.85, "lon": 2.35, "radius_m": 50000},
    },
]


def total_db_hits(plan) -> int:
    """Sum dbHits over the whole profile tree."""
    if plan is None:
        return 0
    hits = plan.get("dbHits", 0) if isinstance(plan, dict) else getattr(plan, "db_hits", 0)
    children = plan.get("children", []) if isinstance(plan, dict) else getattr(plan, "children", [])
    return hits + sum(total_db_hits(child) for child in children)


def operators(plan) -> list[str]:
    """Flatten operator names (depth-first)."""
    if plan is None:
        return []
    name = plan.get("operatorType", "?") if isinstance(plan, dict) else getattr(plan, "operator_type", "?")
    children = plan.get("children", []) if isinstance(plan, dict) else getattr(plan, "children", [])
    return [name.split("@")[0]] + [op for child in children for op in operators(child)]


def measure(client: Neo4jClient, query: str, params: dict) -> dict:
    """Warm up, then PROFILE `RUNS` times; keep the median server time."""
    client.read(query, params)
    timings, hits, ops, rows = [], 0, [], 0
    for _ in range(RUNS):
        rows, plan, elapsed = client.profile(query, params)
        timings.append(elapsed)
        hits, ops = total_db_hits(plan), operators(plan)
    return {"ms": statistics.median(timings), "db_hits": hits, "rows": rows, "operators": ops}


def render(results: list[dict]) -> str:
    """Markdown report."""
    lines = [
        "# Query optimisation benchmarks",
        "",
        f"Generated by `make benchmark` (PROFILE, median of {RUNS} runs, warm cache).",
        "",
        "| Case | Naive db hits | Optimised db hits | Naive ms | Optimised ms | Gain (hits) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for res in results:
        naive, opt = res["naive"], res["optimised"]
        gain = f"x{naive['db_hits'] / opt['db_hits']:.0f}" if opt["db_hits"] else "n/a"
        lines.append(f"| {res['name']} | {naive['db_hits']:,} | {opt['db_hits']:,} | {naive['ms']:.0f} | "
                     f"{opt['ms']:.0f} | {gain} |")
    lines.append("")
    for res in results:
        lines += [
            f"## {res['name']}", "", res["why"], "",
            f"* naive plan: `{' > '.join(res['naive']['operators'][:8])}`",
            f"* optimised plan: `{' > '.join(res['optimised']['operators'][:8])}`", "",
        ]
    return "\n".join(lines)


def main() -> None:
    """CLI entry point."""
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(name)s %(message)s")
    client = Neo4jClient.from_settings(get_settings())
    try:
        results = []
        for case in CASES:
            logger.info(case["name"])
            results.append({
                **case,
                "naive": measure(client, case["naive"], case["params"]),
                "optimised": measure(client, case["optimised"], case["params"]),
            })
    finally:
        client.close()
    OUTPUT.write_text(render(results), encoding="utf-8")
    logger.info(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
